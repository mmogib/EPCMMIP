# VAFBS — Viscosity-Approximation Forward–Backward Splitting (Thong2019 Alg 3.1)
# ============================================================================
#
# Source: Duong Viet Thong and Prasit Cholamjiak, "Strong convergence of a
# forward-backward splitting method with a new step size for solving monotone
# inclusions," Computational and Applied Mathematics 38, Article 94 (2019).
# https://doi.org/10.1007/s40314-019-0855-z. Algorithm 3.1.
#
# Paper notation: solve 0 ∈ A(x) + B(x) with A single-valued monotone Lipschitz
# and B maximal monotone. In this repo's convention, that maps directly to
# `prob.B` (paper A) and `prob.resolvent_A` (paper B).
#
# Iteration:
#   y_n = J^B_{λ_n}(x_n - λ_n A x_n), with λ_n chosen by backtracking over
#         {δ, δℓ, δℓ², ...} until
#           λ_n⟨A x_n - A y_n, x_n - y_n⟩ ≤ μ‖x_n - y_n‖²
#   d_n = x_n - y_n - λ_n(A x_n - A y_n)
#   η_n = (1-μ)‖x_n-y_n‖² / ‖d_n‖²
#   z_n = x_n - γ η_n d_n
#   x_{n+1} = α_n f(x_n) + (1-α_n) z_n
#
# The paper assumes `f` is a contraction. For this repo, we encode the chosen
# contraction `f(x) = c x` via the scalar field `f_scale = c`, keeping the
# algorithm hashable and reproducible (no Function-valued fields). The default
# chosen with the user is `f_scale = 0.9`.

"""
    VAFBS(; delta, ell, mu, gamma, alpha_rule, alpha_scale, f_scale)
    VAFBS(preset::Symbol; kwargs...)

Viscosity-approximation forward-backward splitting method
(Thong–Cholamjiak 2019, Algorithm 3.1).

Fields:
  - `delta > 0` : top line-search step (`δ` in the paper)
  - `ell ∈ (0,1)` : geometric shrink factor (`ℓ` in the paper)
  - `mu ∈ (0,1)` : Armijo-like acceptance parameter (`μ`)
  - `gamma ∈ (0,2)` : correction factor (`γ`)
  - `alpha_rule = :c_over_n` : `α_n = alpha_scale / n`
  - `alpha_scale ∈ (0,1)` : coefficient in `α_n`
  - `f_scale ∈ [0,1)` : contraction `f(x) = f_scale * x`
"""
struct VAFBS <: AbstractAlgorithm
    delta::Float64
    ell::Float64
    mu::Float64
    gamma::Float64
    alpha_rule::Symbol
    alpha_scale::Float64
    f_scale::Float64

    function VAFBS(; delta::Float64, ell::Float64, mu::Float64, gamma::Float64,
                   alpha_rule::Symbol, alpha_scale::Float64, f_scale::Float64)
