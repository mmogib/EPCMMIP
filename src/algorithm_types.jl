# ============================================================================
# MAEFBFP — Modified Adaptive Extrapolated Forward–Backward–Forward
# ============================================================================
#
# MAEFBFP = AEFBFP with the min-rule factor μ replaced by
#   α_n + β_n μ,
# where α_n ≥ 0, β_n ≥ 1, α_n → 0, and β_n → 1. This repo encodes the
# sequences as
#   α_n = alpha_scale / (n+1)^alpha_exp,     alpha_scale ≥ 0, alpha_exp > 0
#   β_n = 1 + beta_scale / (n+1)^beta_exp,   beta_scale ≥ 0, beta_exp > 0
# so the original AEFBFP is recovered at alpha_scale = beta_scale = 0.
#
# This is a repo-side modified variant, not a source-paper algorithm. To stay
# inside the AEFBFP admissibility envelope at every iteration, `solve` enforces
# the sufficient uniform bound
#   α_0 + β_0 μ = alpha_scale + (1 + beta_scale) μ < 1/√6.

"""
    MAEFBFP(; mu, tau_0, xi_rule, sigma_rule,
              alpha_scale, alpha_exp, beta_scale, beta_exp,
              xi_exp, sigma_exp, sigma_scale)
    MAEFBFP(preset::Symbol; kwargs...)

Modified adaptive extrapolated forward–backward–forward method = AEFBFP with
the min-rule factor `mu` replaced by the iteration-dependent coefficient
`alpha_n + beta_n * mu`, where

  - `alpha_n = alpha_scale / (n+1)^alpha_exp`, with `alpha_scale ≥ 0`,
    `alpha_exp > 0`, so `alpha_n → 0`;
  - `beta_n = 1 + beta_scale / (n+1)^beta_exp`, with `beta_scale ≥ 0`,
    `beta_exp > 0`, so `beta_n ≥ 1` and `beta_n → 1`.

The summable additive sequence `ξ_k = 1/(k+1)^xi_exp` (`xi_exp > 1`) and the
Halpern weights `σ_k` are inherited from AEFBFP/EPCM. Validated at `solve`
entry, including the sufficient uniform bound
`alpha_scale + (1 + beta_scale) * mu < 1/sqrt(6)`.
"""
struct MAEFBFP <: AbstractAlgorithm
    mu::Float64
    tau_0::Float64
    xi_rule::Symbol
    sigma_rule::Symbol
    alpha_scale::Float64
    alpha_exp::Float64
    beta_scale::Float64
    beta_exp::Float64
    xi_exp::Float64
    sigma_exp::Float64
    sigma_scale::Float64

    function MAEFBFP(; mu::Float64, tau_0::Float64,
                     xi_rule::Symbol, sigma_rule::Symbol,
                     alpha_scale::Float64, alpha_exp::Float64,
                     beta_scale::Float64, beta_exp::Float64,
                     xi_exp::Float64, sigma_exp::Float64, sigma_scale::Float64)
        return new(mu, tau_0, xi_rule, sigma_rule,
                   alpha_scale, alpha_exp, beta_scale, beta_exp,
                   xi_exp, sigma_exp, sigma_scale)
    end
end

