# ============================================================================
# s30: Main benchmark — 5 methods × 4 problems × dims × seeds (tuned-vs-tuned)
# ============================================================================
#
# Runs every method at its s25-PROMOTED per-problem config (read from the
# generated results/tuned_params.jl) on the full suite, recording results under
# script='s30'. This is the head-to-head comparison for the paper.
#
#   - Tuned params : include(results/tuned_params.jl) → TUNED_PARAMS, TUNED_CONVERGED.
#                    Each method is built as T(:Pk; TUNED_PARAMS[(name(T),Pk)]...).
#   - Tolerance    : eps = native_tol(P) (D1, source-paper criterion).
#   - Budget       : maxiter = universal_maxiter(P, eps) (tolerance-aware, uniform).
#   - Stopping     : NativeResStopping(native, eps) + MaxIterStopping + NanStopping.
#   - Dims/seeds   : P1{64,128,256} P2{100,300,600,900} P3{K=100} P4{256,512};
#                    20 seeds for P3, 10 otherwise (3 each under --quick).
#   - CPU timing   : `reps` solves per cell (default 3; iters/flag/residual are
#                    deterministic — taken from rep 1; cpu_time = median over reps).
#   - History      : collected for ONE representative cell per (method,problem)
#                    (reference dim, seed1) so s70 can draw convergence panels.
#   - DNC          : EPCM on P4 is expected DNC at native tol (TUNED_CONVERGED) —
#                    recorded honestly as flag=:maxiter, not a crash.
#
# Usage:
#   julia --project=jcode jcode/scripts/s30_benchmark.jl
#   julia --project=jcode jcode/scripts/s30_benchmark.jl --quick
#   julia --project=jcode jcode/scripts/s30_benchmark.jl --methods=EPCM,IFRAB --problems=P2,P3 --reps=5 --force
# Output: console + results/logs/log_s30_benchmark_<ts>.txt ; rows tagged script='s30'.
# Skips already-done cells unless --force.

include(joinpath(@__DIR__, "..", "src", "includes.jl"))
using Statistics

# ── tuned params (generated by s25) ─────────────────────────────────────────
const TUNED_JL = joinpath(JCODE_ROOT, "results", "tuned_params.jl")
isfile(TUNED_JL) ||
    error("s30: $(TUNED_JL) not found. Run the s20 sweep (all method×problem cells) then s25 first.")
include(TUNED_JL)   # defines const TUNED_PARAMS, TUNED_CONVERGED

const S30_METHODS    = (EPCM, MTTM, IMTTM, IFRAB, SFRBM)        # reporting order
const S30_PROBLEMS   = ("P1", "P2", "P3", "P4")
const S30_DIMS       = Dict("P1" => [64, 128, 256], "P2" => [100, 300, 600, 900],
                            "P3" => [100], "P4" => [256, 512])
const S30_REFDIM     = Dict("P1" => 128, "P2" => 300, "P3" => 100, "P4" => 256)  # history cell
const METHOD_BY_NAME = Dict(name(T) => T for T in S30_METHODS)

# ── tiny ARG parser ──────────────────────────────────────────────────────────
function parse_cli(args)
    opts = Dict{String,String}(); flags = String[]
    for a in args
        startswith(a, "--") || continue
        kv = split(a[3:end], "="; limit = 2)
        length(kv) == 2 ? (opts[kv[1]] = kv[2]) : push!(flags, kv[1])
    end
    return opts, flags
end

# Build a method at its tuned per-problem config.
function build_alg(::Type{T}, P::AbstractString) where {T}
    key = (name(T), P)
    haskey(TUNED_PARAMS, key) ||
        error("s30: no tuned params for $key in tuned_params.jl — re-run s25 (did s20 tune this cell?).")
    return T(Symbol(P); TUNED_PARAMS[key]...)
end

# Run one (method, problem, dim, seed) cell with `reps` timing repetitions.
# Returns a NamedTuple summary, or `nothing` if skipped.
function run_cell(db, T, prob, P, dim, init, eps, maxiter, reps, run_id;
                  collect_hist::Bool, force::Bool)
    alg        = build_alg(T, P)
    hash, hin  = make_config_hash(alg, P, eps, maxiter)
    ensure_config!(db, alg, P, eps, maxiter, hash, hin)
    if !force && is_done(db, hash, P, dim, init.label; script = "s30")
        return nothing
    end

    cpus         = Float64[]
    hist_records = IterRecord[]
    local result, nat
    for rep in 1:reps
        # Fresh stoppers each rep (ResidualStopping/NativeResStopping carry de-bounce state).
        stopping = (NativeResStopping(prob.native_residual, eps),
                    MaxIterStopping(maxiter), NanStopping())
        nrec = NativeResRecorder(prob.native_residual)
        if rep == 1 && collect_hist
            hc     = HistoryCallback()
            result = solve(alg, prob, copy(init.x0); stopping = stopping, observers = (hc, nrec))
            hist_records = hc.history
        else
            result = solve(alg, prob, copy(init.x0); stopping = stopping, observers = (nrec,))
        end
        push!(cpus, result.cpu_time)
        nat = nrec.value
    end

    med_cpu = median(cpus)
    # SolverResult is immutable; reconstruct with the median CPU (other fields deterministic).
    result_med = make_result(converged = result.converged, iterations = result.iterations,
                             f_evals = result.f_evals, cpu_time = med_cpu, x = result.x,
                             flag = result.flag, residual = result.residual,
                             scaled_residual = result.scaled_residual)
    insert_result!(db, hash, P, dim, init.label, init.seed_idx, run_id, result_med;
                   script = "s30", native_residual = nat)
    if collect_hist && !isempty(hist_records)
        insert_history!(db, hash, P, dim, init.label, init.seed_idx, hist_records; script = "s30")
    end
    return (converged = result.converged, iters = result.iterations,
            cpu = med_cpu, flag = result.flag, nat = nat)
end

# Final summary: aggregate ALL s30 rows in the DB (robust to skips) per (method, problem).
function print_s30_summary(db, tee)
    df = DBInterface.execute(db, """
        SELECT c.method AS method, r.problem AS problem, r.converged AS conv,
               r.iterations AS iters, r.cpu_time AS cpu
        FROM results r JOIN configs c ON r.config_hash = c.config_hash
        WHERE r.script='s30'
    """) |> DataFrame
    println(tee, "\n--- s30 summary (median over seeds & dims; all s30 rows) ---")
    @printf(tee, "  %-6s %-4s %8s %10s %12s\n", "method", "prob", "conv", "med_iter", "med_cpu(s)")
    println(tee, "  " * "-" ^ 46)
    med(v) = isempty(v) ? NaN : median(v)
    for T in S30_METHODS, P in S30_PROBLEMS
        sub = df[(df.method .== name(T)) .& (df.problem .== P), :]
        nrow(sub) == 0 && continue
        conv = sub[sub.conv .== 1, :]
        mi   = isempty(conv) ? "—" : string(Int(round(med(float.(conv.iters)))))
        mc   = isempty(conv) ? med(float.(sub.cpu)) : med(float.(conv.cpu))
        @printf(tee, "  %-6s %-4s %4d/%-3d %10s %12.4f\n",
                name(T), P, nrow(conv), nrow(sub), mi, mc)
    end
end

function main()
    opts, flags = parse_cli(ARGS)
    quick = "quick" in flags
    force = "force" in flags
    reps  = haskey(opts, "reps") ? parse(Int, opts["reps"]) : (quick ? 1 : 3)
    methods = haskey(opts, "methods") ?
        Tuple(METHOD_BY_NAME[String(strip(m))] for m in split(opts["methods"], ",")) : S30_METHODS
    problems = haskey(opts, "problems") ?
        String[String(strip(p)) for p in split(opts["problems"], ",")] : collect(S30_PROBLEMS)

    logpath, tee, _ = setup_logging("s30_benchmark")
    db     = open_db()
    run_id = "s30_$(Dates.format(now(), "yyyymmdd_HHMMSS"))"
    mlist  = join(name.(methods), ",")
    plist  = join(problems, ",")

    println(tee, "=" ^ 80)
    println(tee, "  s30 benchmark — tuned-vs-tuned, 5 methods × suite   $(Dates.now())")
    println(tee, "  reps=$reps  quick=$quick  force=$force  run_id=$run_id")
    println(tee, "  methods=$mlist  problems=$plist")
    println(tee, "=" ^ 80)

    n_run = 0; n_skip = 0; n_err = 0
    for P in problems
        prob_id = parse(Int, P[2:end])
        eps     = native_tol(P)
        maxiter = universal_maxiter(P, eps)
        n_seeds = quick ? 3 : (P == "P3" ? 20 : 10)
        dims    = quick ? [S30_REFDIM[P]] : S30_DIMS[P]
        for dim in dims
            prob = P == "P3" ? get_problem(3; n_seeds = n_seeds) :
                               get_problem(prob_id; dim = dim, n_seeds = n_seeds)
            rdim = prob.dim
            inits = get_initial_points(prob)
            for T in methods
                expected_dnc = haskey(TUNED_CONVERGED, (name(T), P)) && !TUNED_CONVERGED[(name(T), P)]
                cell = NamedTuple[]
                for init in inits
                    collect_hist = (rdim == S30_REFDIM[P]) && (init.seed_idx == 1)
                    try
                        r = run_cell(db, T, prob, P, rdim, init, eps, maxiter, reps, run_id;
                                     collect_hist = collect_hist, force = force)
                        if r === nothing
                            n_skip += 1
                        else
                            n_run += 1
                            push!(cell, r)
                        end
                    catch e
                        n_err += 1
                        @printf(tee, "  %-6s %-3s dim=%-4d %-8s *** EXCEPTION ***\n",
                                name(T), P, rdim, init.label)
                        showerror(tee, e, catch_backtrace()); println(tee)
                    end
                end
                if !isempty(cell)
                    nconv = count(c -> c.converged, cell)
                    mi    = nconv > 0 ? string(Int(round(median([float(c.iters) for c in cell if c.converged])))) : "—"
                    mc    = median([c.cpu for c in cell])
                    @printf(tee, "  %-6s %-3s dim=%-4d  %3d/%-3d conv  med_iter=%-8s med_cpu=%.4f%s\n",
                            name(T), P, rdim, nconv, length(cell), mi, mc,
                            expected_dnc ? "   [expected DNC @ native tol]" : "")
                end
            end
        end
    end

    @printf(tee, "\n  Cells: %d run, %d skipped (already done), %d errored.\n", n_run, n_skip, n_err)
    print_s30_summary(db, tee)
    println(tee, "\n  Done. Rows tagged script='s30'. Next: s70 figures/tables.")
    teardown_logging(tee, logpath)
    return nothing
end

main()
